#!/usr/bin/env python3
"""Render the attributed JSON witness as Lean and check exact source agreement."""

import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()

data = (root / "median11_25.json").read_bytes()
pairs = json.loads(data)
if len(pairs) != 25:
    raise SystemExit("expected exactly 25 comparator pairs")
for pair in pairs:
    if (not isinstance(pair, list) or len(pair) != 2
        or any(type(port) is not int for port in pair)
        or not 0 <= pair[0] < pair[1] < 11):
        raise SystemExit(f"invalid comparator {pair!r}")

lines = ",\n".join(f"  ⟨{a}, {b}, by decide⟩" for a, b in pairs)
module = f"""-- Generated by scripts/generate-lean-witness.py from median11_25.json.
-- Construction by Bert Dobbelaere. See THIRD-PARTY.md for attribution.
-- JSON SHA-256 {hashlib.sha256(data).hexdigest()}
import Median11.Network

namespace Median11

def published : Network 11 := [
{lines}
]

end Median11
"""
path = root / "formal" / "Median11" / "Witness.lean"
if args.check:
    if path.read_bytes() != module.encode():
        raise SystemExit("Lean witness differs from the canonical JSON")
else:
    path.write_text(module, encoding="utf-8")
